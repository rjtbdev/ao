#!/usr/bin/env python3
"""
embed_panel.py -- bake panel.html into a C header as a string literal.

Usage:
    python embed_panel.py <panel.html> <out_header.h>

Reads the built panel HTML (from shmr-panel/dist/panel.html or directly from
shmr-panel/index.html for a dev embed) and writes a C header containing:

    static const char g_panel_html[] = "...";

The loader's ws_server.c includes this header and uses g_panel_html as the
fallback when panel.html is not present on disk next to the exe.
"""
import sys, re

def escape_c(s: str) -> str:
    out = []
    for ch in s:
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '\n': out.append('\\n"\n"')
        elif ch == '\r': pass
        else: out.append(ch)
    return ''.join(out)

def main():
    if len(sys.argv) != 3:
        print(f'usage: {sys.argv[0]} <panel.html> <out.h>')
        sys.exit(1)

    src, dst = sys.argv[1], sys.argv[2]
    with open(src, encoding='utf-8') as f:
        html = f.read()

    # collapse runs of whitespace between tags to reduce embed size
    html = re.sub(r'>\s+<', '><', html)
    html = re.sub(r'\s{2,}', ' ', html)

    escaped = escape_c(html.strip())

    header = f'''\
/* auto-generated by embed_panel.py — do not edit */
#pragma once
static const char g_panel_html[] =
"{escaped}";
'''
    with open(dst, 'w', encoding='utf-8') as f:
        f.write(header)

    print(f'[embed] {src} -> {dst}  ({len(html)} bytes)')

if __name__ == '__main__':
    main()
